"""One command that decides whether the repository is ready to release.

    python tools/release_check.py [--allow-dirty]

Writes results/release_check.md and exits 1 if any check fails. Checks that need local data
(the image features) are reported as skipped, not passed, when that data is absent.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = sys.executable
EXAMPLES = ["pvc_example.jpg", "nylon_example.jpg", "few_particles_example.jpg"]
REQUIRED = ["LICENSE", "CITATION.cff", "MODEL_CARD.md", "DATASET_CARD.md", "README.md",
            "RELEASE_NOTES.md", "docs/analyse.schema.json"]


def run(cmd: list[str], timeout: int = 1800) -> tuple[int, str]:
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf8", errors="replace",
                       timeout=timeout)
    return r.returncode, (r.stdout + r.stderr).strip()


def git(*a: str) -> str:
    return run(["git", *a])[1]


def check_git(allow_dirty: bool) -> tuple[str, str]:
    dirty = git("status", "--porcelain", "--untracked-files=no")
    info = f"branch {git('rev-parse', '--abbrev-ref', 'HEAD')}, commit {git('rev-parse', '--short', 'HEAD')}"
    if dirty and not allow_dirty:
        return "fail", f"{info}; uncommitted changes in tracked files:\n{dirty[:400]}"
    return "pass", info + ("; tree has uncommitted changes (allowed)" if dirty else "; tree is clean")


def check_cmd(cmd: list[str]) -> tuple[str, str]:
    rc, out = run(cmd)
    tail = "\n".join(out.splitlines()[-3:])
    return ("pass" if rc == 0 else "fail"), tail


def check_analyse_schema() -> tuple[str, str]:
    if not (ROOT / "data" / "processed" / "particles_resample.csv.gz").exists():
        return "skipped", "needs `make features` (image features) and the dataset"
    import jsonschema

    schema = json.loads((ROOT / "docs" / "analyse.schema.json").read_text(encoding="utf8"))
    notes = []
    for i, name in enumerate(EXAMPLES):
        cmd = [PY, "-m", "mp.cli", "analyse", "--image", f"app/examples/{name}", "--json"]
        if i == 0:
            cmd += ["--sensors", "160", "70", "64", "64"]
        rc, out = run(cmd)
        if rc != 0:
            return "fail", f"{name}: command failed\n{out[-300:]}"
        try:
            jsonschema.validate(json.loads(out[out.index("{"):]), schema)
        except Exception as exc:
            return "fail", f"{name}: {type(exc).__name__}: {str(exc)[:200]}"
        notes.append(name)
    return "pass", f"{len(notes)} outputs valid against the schema"


def check_files() -> tuple[str, str]:
    missing = [f for f in REQUIRED if not (ROOT / f).exists()]
    if missing:
        return "fail", "missing: " + ", ".join(missing)
    return "pass", f"{len(REQUIRED)} files present"


def open_placeholders() -> tuple[str, str]:
    hits = []
    for f in git("ls-files").splitlines():
        if f in ("tools/release_check.py", "tools/claims_audit.py"):
            continue
        if f.endswith((".png", ".pdf", ".docx", ".zip")):
            continue
        p = ROOT / f
        try:
            text = p.read_text(encoding="utf8")
        except Exception:
            continue
        n = len(re.findall("TODO-after-upload", text))
        if n:
            hits.append(f"{f} ({n})")
    return "info", ("open placeholders: " + ", ".join(hits)) if hits else "none"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-dirty", action="store_true")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf8", errors="replace")
    checks = [
        ("Git state", lambda: check_git(args.allow_dirty)),
        ("Lint (ruff)", lambda: check_cmd([PY, "-m", "ruff", "check", "."])),
        ("Tests (pytest)", lambda: check_cmd([PY, "-m", "pytest", "-q"])),
        ("Claims audit", lambda: check_cmd([PY, "tools/claims_audit.py"])),
        ("Reviewer-response claims against evidence", lambda: check_cmd(
            [PY, "tools/claims_vs_evidence.py", "--check"])),
        ("Paper assets consistency", lambda: check_cmd(
            [PY, "-m", "pytest", "-q", "tests/test_paper_assets.py"])),
        ("`mp analyse` output schema", check_analyse_schema),
        ("Required files", check_files),
        ("Open placeholders", open_placeholders),
    ]
    rows, failed = [], 0
    for name, fn in checks:
        t = time.time()
        try:
            status, detail = fn()
        except Exception as exc:
            status, detail = "fail", f"{type(exc).__name__}: {exc}"
        failed += status == "fail"
        rows.append((name, status, detail, time.time() - t))
        print(f"{status.upper():7} {name} ({time.time() - t:.0f}s)")
    L = ["# Release check", "", "Generated by `python tools/release_check.py`.", "",
         "| Check | Result | Detail |", "|---|---|---|"]
    for name, status, detail, _ in rows:
        L.append(f"| {name} | {status} | {detail.replace(chr(10), '<br>').replace('|', '/')} |")
    L += ["", "Result: " + ("FAILED" if failed else "passed")]
    (ROOT / "results" / "release_check.md").write_text("\n".join(L) + "\n", encoding="utf8", newline="\n")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
