def fig_angular() -> list[Path]:
    from mp.scatter import generate as G
    from mp.scatter import mie
    from mp.scatter import optics as O

    cfg = G.load_scatter_config()
    rig = O.rig_from_config(cfg)
    theta = np.concatenate([np.linspace(0.1, 6, 300), np.linspace(6, 180, 600)[1:]])
    k = 2 * np.pi * rig.n_medium / (rig.wavelength_nm * 1e-9)
    fig, ax = plt.subplots(figsize=(4.6, 3.2))
    x = float(mie.size_parameter(50.0, rig.wavelength_nm, rig.n_medium))
    for pol, ls in (("PVC", "-"), ("NYLON", "--")):
        p = cfg["polymers"][pol]
        m = mie.relative_index(p["n"], p["k"], rig.n_medium)
        ax.semilogy(theta, mie.angular_intensity(m, x, theta)["unpolarised"] / k**2, ls, label=pol, lw=1)
    for t in rig.theta_deg:
        ax.axvline(t, color="gray", lw=0.6, ls=":")
    ax.set_xlabel("scattering angle (deg)")
    ax.set_ylabel(r"d$\sigma$/d$\Omega$ (m$^2$/sr)")
    ax.legend(frameon=False)
    return _save(fig, "angular_scattering")


def write_figures() -> list[Path]:
    paths = []
    for fn in (fig_controls, fig_feature_sets, fig_regression, fig_importance, fig_angular):
        paths += fn()
    # photographs: unchanged content, no titles of our own
    from PIL import Image

    for name in ("segmentation_examples", "montage_PVC", "montage_NYLON"):
        src = ROOT / "results" / "figures" / f"{name}.png"
        if src.exists():
            im = Image.open(src).convert("RGB")
            (OUT / "figures").mkdir(parents=True, exist_ok=True)
            im.save(OUT / "figures" / f"{name}.png", dpi=(300, 300))
            im.save(OUT / "figures" / f"{name}.pdf", resolution=300)
            paths += [OUT / "figures" / f"{name}.png", OUT / "figures" / f"{name}.pdf"]
    return paths


def write_manifest(files: list[Path]) -> Path:
    L = ["# paper_assets", "",
         "Generated by `python -m mp.cli paper-assets` from `results/`. Only this manifest is tracked.", "",
         "| File | Source |", "|---|---|"]
    src = {"numbers.tex": "named numbers (see `NUMBERS` in `src/mp/paper/assets.py`)"}
    for f in sorted(files):
        rel = f.relative_to(OUT).as_posix()
        L.append(f"| {rel} | {src.get(rel, 'results/*.json')} |")
    p = OUT / "MANIFEST.md"
    p.write_text("\n".join(L) + "\n", encoding="utf8", newline="\n")
    return p


def run() -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    with plt.rc_context(STYLE):
        files = [write_numbers()] + write_tables() + write_figures()
    write_manifest(files)
    return {"files": len(files), "dir": str(OUT)}
