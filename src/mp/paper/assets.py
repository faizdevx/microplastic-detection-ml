def number_value(name: str):
    f, k, _ = NUMBERS[name]
    if "{best}" in k:  # model selected by the E1 rule in results/phase3_selected.json
        k = k.replace("{best}", J("results/phase3_selected.json")["model"])
    return key(J(f), k)


def write_numbers() -> Path:
    L = ["% Generated by `python -m mp.cli paper-assets`; do not edit by hand."]
    for name, (_f, _k, fmt) in NUMBERS.items():
        v = number_value(name)
        v = int(v) if "d" in fmt else float(v)
        L.append(f"\\newcommand{{\\{name}}}{{{fmt.format(v)}}}")
    p = OUT / "numbers.tex"
    p.write_text("\n".join(L) + "\n", encoding="utf8", newline="\n")
    return p


def parse_numbers_tex(path: Path) -> dict:
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", path.read_text(encoding="utf8")))


