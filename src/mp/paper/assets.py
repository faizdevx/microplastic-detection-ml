def table_probes() -> pd.DataFrame:
    p = J("results/phase5_probe.json")
    rows = []
    for n, v in p.items():
        if not isinstance(v, dict) or "probe" not in v:
            continue
        q = v["probe"]
        rows.append({"Features": n,
                     "Exposure overall": f3(q["exposure_overall"]["accuracy"]),
                     "Exposure within class": f3(q["exposure_within_class"]["accuracy"]),
                     "Resolution": f3(q["resolution"]["accuracy"]),
                     "Coupling": f3(v["prediction_coupling"]["mean_abs"])})
    return pd.DataFrame(rows)


def table_regression() -> pd.DataFrame:
    reg = J("results/phase3_regression.json")
    rows = []
    for sch, res in reg["E1"]["schemes"].items():
        for n, v in res.items():
            ci = v["ci95"]["r2"]
            rows.append({"Scheme": sch, "Model": n, "R2": f3(v["r2"]), "R2 CI": f"{ci[0]:.3f} to {ci[1]:.3f}",
                         "RMSE": f3(v["rmse"]), "MAE": f3(v["mae"]), "MAPE %": f"{v['mape_pct']:.1f}",
                         "Coverage 90": f"{v['conformal']['empirical_coverage']:.2f}"})
    rob = reg["robustness"]["variants"]["rebaselined_per_geometry"]
    for n, per in rob.items():
        rows.append({"Scheme": "robustness (log10 R2, all other geometries)", "Model": n,
                     "R2": f3(per["all_others"]["log10_scale"]["r2"]), "R2 CI": "", "RMSE": "", "MAE": "",
                     "MAPE %": "", "Coverage 90": f"{per['all_others']['conformal_coverage']:.2f}"})
    return pd.DataFrame(rows)


