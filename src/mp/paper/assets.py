def write_tables() -> list[Path]:
    out = []
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    for name, (fn, caption) in TABLES.items():
        df = fn()
        csv_p, tex_p = OUT / "tables" / f"{name}.csv", OUT / "tables" / f"{name}.tex"
        df.to_csv(csv_p, index=False, lineterminator="\n")
        tex_p.write_text(to_latex(df, caption, name), encoding="utf8", newline="\n")
        out += [csv_p, tex_p]
    return out


# ----------------------------------------------------------------------- figures --------
def _save(fig, name: str) -> list[Path]:
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    paths = []
    for ext in ("png", "pdf"):
        p = OUT / "figures" / f"{name}.{ext}"
        fig.savefig(p, dpi=300, bbox_inches="tight")
        paths.append(p)
    plt.close(fig)
    return paths


def fig_controls() -> list[Path]:
    v = J("results/phase5_variants.json")["results"]
    names = list(v)
    x = np.arange(len(names))
    w = 0.2
    series = [("CV accuracy", [v[n]["cv"]["accuracy"] for n in names]),
              ("640 to 1280", [v[n]["cross_resolution"]["a_to_b"]["balanced_accuracy"] for n in names]),
              ("1280 to 640", [v[n]["cross_resolution"]["b_to_a"]["balanced_accuracy"] for n in names]),
              ("Background discs", [v[n]["pseudo_particles"]["balanced_accuracy"] for n in names])]
    fig, ax = plt.subplots(figsize=(6.4, 3.0))
    for i, (lab, vals) in enumerate(series):
        ax.bar(x + (i - 1.5) * w, vals, w, label=lab)
    ax.axhline(0.5, color="k", lw=0.6, ls="--")
    ax.set_xticks(x, [n.split("_")[0] for n in names])
    ax.set_ylabel("accuracy / balanced accuracy")
    ax.set_ylim(0.4, 1.02)
    ax.legend(ncol=4, loc="lower center", bbox_to_anchor=(0.5, 1.0), frameon=False)
    return _save(fig, "controls_by_variant")


