def fig_regression() -> list[Path]:
    rows = J("results/phase3_regression.json")["E1"]["schemes"]["by_concentration_level"]
    names = list(rows)
    r2 = np.array([rows[n]["r2"] for n in names])
    lo = np.array([rows[n]["ci95"]["r2"][0] for n in names])
    hi = np.array([rows[n]["ci95"]["r2"][1] for n in names])
    fig, ax = plt.subplots(figsize=(6.4, 3.0))
    ax.bar(names, r2, yerr=[np.clip(r2 - lo, 0, None), np.clip(hi - r2, 0, None)], capsize=3,
           color=OKABE_ITO[0])
    ax.set_ylabel("R$^2$ (95 % CI)")
    ax.set_ylim(0, 1)
    ax.tick_params(axis="x", rotation=30)
    return _save(fig, "regression_e1")


