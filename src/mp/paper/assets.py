def J(rel: str):
    return json.loads((ROOT / rel).read_text(encoding="utf8"))


def key(obj, path: str):
    for part in re.findall(r"[^.\[\]]+|\[\d+\]", path):
        obj = obj[int(part[1:-1])] if part.startswith("[") else obj[part]
    return obj


